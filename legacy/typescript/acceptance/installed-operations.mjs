import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mcpParent } from './mcp-parent.mjs';
import { readFile, writeFile, lstat } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { installedHarness } from './installed-harness.mjs';
import { exec } from './live-harness.mjs';
import { connect } from '../test/harness.mjs';

test('Installed Node 24 package: doctor, interactive console and actual Codex MCP Parent', async t => {
  const h = await installedHarness(t), { terminal, installation } = h;
  const env = { ...process.env, PATH: `${dirname(process.execPath)}:${process.env.PATH}` };
  const doctor = JSON.parse((await exec(installation.executable, ['doctor'], { env })).stdout);
  assert.equal(doctor.ok, true, JSON.stringify(doctor));
  assert.equal(doctor.pane_input_attempts, 0);
  const directory = dirname(terminal.ready.socket);
  const permissions = {};
  for (const name of ['', 'authority.sqlite', 'ledger.sqlite', 'ledger.identity', 'core.sock']) {
    const info = await lstat(join(directory, name));
    permissions[name || 'directory'] = info.mode & 0o777;
    assert.equal(info.mode & 0o777, name === '' ? 0o700 : 0o600);
  }
  const client = await connect(terminal.ready.socket, t);
  const pane = await client.call('pane_describe', { pane_id: h.pane.pane_id });
  await terminal.command(`mode ${pane.pane_session_id} 1`);
  const parent = await mcpParent(t, installation, h.root, `This is authorized installed-package acceptance, with an owned disposable Herdr pane ${h.pane.pane_id} and cwd ${h.root}. Use only herdr_broker MCP. Describe exact pane. Start one job objective "Inspect installed package workflow" with action_scope {"profile":"local_posix","cwd":${JSON.stringify(h.root)},"paths":[${JSON.stringify(h.root)}],"trusted":true}. Wait for result_ready and read first-row Evidence. Propose exactly "printf 'INSTALL_PROBE\\n'" with explicit cwd/env and bounded paths and your risk assessment. The session is mode 1: call action_status to confirm approval_required. Do not submit or request approval; the test intentionally checks pending state and purge. Cancel your job, then briefly report observed facts in Korean. No input should be sent.`);
  const { code, calls, values } = parent;
  assert.equal(code, 0);
  assert.ok(values.some(item => item.tool === 'action_status' && item.value.authorization === 'approval_required'), JSON.stringify(parent));
  for (const tool of ['pane_describe', 'job_start', 'job_wait', 'evidence_get', 'action_propose', 'action_status', 'job_cancel']) assert.ok(calls.some(call => call.tool === tool), tool);
  const status = await terminal.command('status');
  const proposal = status.proposals[0];
  assert.equal(status.sessions[0].action_mode, 1);
  assert.equal(status.jobs[0].ordinary_attempts_remaining, 3);
  assert.ok(!JSON.stringify(status).includes('INSTALL_PROBE'));
  await terminal.command('purge all');
  const purged = await terminal.command(`review ${proposal.proposal_id}`);
  assert.equal(purged.payload, undefined);
  assert.equal(purged.authorization, 'blocked');
  assert.equal((await terminal.command(`approve ${proposal.proposal_id}`)).error, 'proposal_invalid');
  const files = ['ledger.sqlite', 'ledger.sqlite-wal', 'authority.sqlite'];
  for (const name of files) assert.ok(!(await readFile(join(directory, name))).includes(Buffer.from('INSTALL_PROBE')));
  assert.equal(h.calls.filter(call => call.method === 'pane.send_input').length, 0);
  const facade = spawn(installation.executable, ['mcp'], { env, stdio: 'pipe' });
  let protocol = ''; facade.stdout.on('data', chunk => { protocol += chunk; });
  facade.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-11-25', capabilities: {}, clientInfo: { name: 'installed-probe', version: '1' } } }) + '\n');
  await new Promise(resolve => setTimeout(resolve, 100));
  facade.stdin.write(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }) + '\n');
  facade.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: 2, method: 'tools/list' }) + '\n');
  await new Promise(resolve => setTimeout(resolve, 100));
  facade.stdin.end();
  await new Promise(resolve => facade.once('close', resolve));
  const replies = protocol.trim().split('\n').filter(Boolean).map(JSON.parse);
  assert.equal(replies.find(reply => reply.id === 2).result.tools.length, 10);
  assert.equal((await terminal.command('status')).job_count, status.job_count);
  const record = { at: new Date().toISOString(), installation, doctor, permissions, actual_parent: { code, elapsed_ms: parent.elapsed_ms, mcp_command: installation.executable, tools: values, usage: parent.usage, stderr_bytes: parent.stderr_bytes }, facade_protocol: replies.map(reply => ({ id: reply.id, initialized: !!reply.result?.serverInfo, tools: reply.result?.tools?.map(tool => tool.name) })), purge_pending: 'body absent; approval blocked', pane_input_attempts: 0, state_body_matches: 0 };
  await writeFile(new URL('../docs/implementation/issue-23-installed-acceptance.json', import.meta.url), JSON.stringify(record, null, 2).replaceAll(h.root, '<disposable-cwd>') + '\n');
});
